#!/bin/bash
# usage: package.sh  (builds exe from current tree, stages program-only zip; does NOT upload)
set -e
cd ~/raabt/shell
GOOS=windows GOARCH=amd64 CGO_ENABLED=0 go build -trimpath -ldflags "-s -w -H windowsgui" -o /tmp/pkg/raabt.exe .
cd /tmp/pkg && rm -rf Raabt && mkdir -p Raabt/LICENSES && cp raabt.exe Raabt/ && cp ~/raabt/assets/raabt-icon.ico Raabt/
cp ~/raabt/LICENSES/* Raabt/LICENSES/
cat > Raabt/اقرأني-README.txt <<'EOT'
راابط
- مفيش تثبيت: شغّل raabt.exe. محتاج Microsoft Edge WebView2 Runtime موجود على الجهاز.
- بياناتك (الخزنة، الصور، النسخ الاحتياطية، الخطوط اللي بتضيفها، وملفات WebView2) بتتحفظ في فولدر Raabt-data جنب البرنامج.
- للتحديث: اقفل البرنامج، انسخ فولدر Raabt-data في مكان تاني، وبدّل raabt.exe بس. متمسحش Raabt-data.
- التشغيل مع ويندوز والاختصار العام مش بيشتغلوا غير لما تفعّلهم من الإعدادات.
- الخطوط: خطوطك السبعة اللي بعتهم مدمجة بناءً على طلبك، ومعاهم Playpen (OFL) وباقي الخطوط المفتوحة. حقوق التوزيع مش متأكد منها: ملف "ملهم" مكتوب فيه "Please do not sell or redistribute" وملف "هالة جميل" عليه علامة ترخيص مقيّد، وباقي الملفات من غير نص ترخيص واضح (UKIJ تحت LGPL). فخلّي البرنامج على جهازك بس ومتبعتوش أو تنشره. التفاصيل في LICENSES/PERSONAL-FONTS.txt.
- تصدير PDF بيتحفظ مباشرة من غير نافذة طباعة، بشجرة المجلدات وأسماء الروابط قابلة للضغط. النص جوّه الـPDF صورة (مش بيتحدد ولا بيتبحث فيه).
- مكتبة الصور: 41 صورة جاهزة (منها 16 صورة جديدة بعتها انت)، وتقدر تضيف صور من جهازك.
- قسم المواد: تضيف مواد (كورسات)، وجوّه كل مادة مجلدات وروابط بتاعتها. وتقدر تضيف أي مجلد أو رابط من الخزنة لمادة.
- حالات المواد: "لسه هسجلهم ان شاء الله" و"مسجلهم" و"مخلصهم"، وزر "تعديل الحالات" بيخليك تغيّر أسماءهم أو تضيف حالة جديدة أو تحذف واحدة، وتغيّر حالة أي مادة في أي وقت.
- الاستيراد بيسألك: استيراد جديد ولا كتابة فوق استيراد نفس المتصفح القديم، مع تأكيد قبل التنفيذ وتراجع بعدها. الكتابة فوق بتحافظ على تعديلاتك (اسم، صورة، تاج، ملاحظة).
- التصدير والنسخ الاحتياطي: تقدر تختار مجلدات وروابط معيّنة تتصدّر (HTML للمتصفح، Excel، Word، PDF) أو تتعمل لها نسخة.
- النسخ التلقائي: كل عدد ساعات تحدده، أو يوم/أسبوع/شهر، ومكان الحفظ تختاره من الإعدادات.
- ملاحظة قصيرة لكل رابط، بتظهر تحت اسمه وبتتضمنها نسخ Excel وWord.
- بحث سريع من أي مكان بـ Ctrl+K أو Ctrl+F، وبحث في القسم الحالي أو كل الأقسام، مع فلتر بالمادة أو التاج.
- فحص الروابط اللي مش بتفتح عند الطلب (مجلد معيّن أو الخزنة كلها)، وفتح كل روابط أي مجلد بضغطة.
- البرنامج ده ما اتجرّبش على ويندوز حقيقي من ناحيتي. لو لقيت حاجة مش شغالة قولّي.
EOT
rm -f /tmp/raabt-final.zip && (cd /tmp/pkg && zip -qr /tmp/raabt-final.zip Raabt) && sha256sum /tmp/pkg/raabt.exe /tmp/raabt-final.zip
