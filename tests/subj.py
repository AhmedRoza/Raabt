import asyncio
from playwright.async_api import async_playwright
R=[]
def ok(n,c,x=''): R.append(bool(c)); print('PASS' if c else 'FAIL',n,x,flush=True)
async def main():
  async with async_playwright() as p:
    b=await p.chromium.launch(executable_path='/usr/bin/google-chrome',args=['--no-sandbox'])
    pg=await b.new_page(viewport={'width':1180,'height':820}); errs=[]
    pg.on('pageerror',lambda e:errs.append(str(e))); pg.set_default_timeout(6000)
    await pg.goto('file:///tmp/test.html'); await pg.wait_for_timeout(600)
    await pg.evaluate("S.vault=[{kind:'folder',id:'V1',title:'شغل',color:'#7c5cff',shape:0,children:[{kind:'link',id:'L1',title:'Example',url:'https://example.com'}]},{kind:'link',id:'L2',title:'موقع تاني',url:'https://other.test'}];S.subjects=[];S.imports=[];prep(S.vault);render()")

    await pg.click('nav button[data-tab="subjects"]'); await pg.wait_for_timeout(300)
    ok('subjects tab shows add button',await pg.evaluate("!!document.querySelector('[data-act=addsubject]')"))
    await pg.click('[data-act=addsubject]'); await pg.wait_for_timeout(300)
    await pg.fill('#dlg input[name=title]','رياضيات 2'); await pg.click('[data-ok="1"]'); await pg.wait_for_timeout(400)
    ok('subject created',await pg.evaluate("S.subjects.length===1&&S.subjects[0].title==='رياضيات 2'"))
    await pg.screenshot(path='/downloads/shot_subj_root.png')

    await pg.evaluate("enter(S.subjects[0].id)"); await pg.wait_for_timeout(300)
    await pg.evaluate("void addFolder('subjects')"); await pg.wait_for_timeout(250)
    await pg.fill('#dlg input[name=title]','محاضرات'); await pg.click('[data-ok="1"]'); await pg.wait_for_timeout(300)
    ok('folder inside subject',await pg.evaluate("S.subjects[0].children.length===1"))
    await pg.evaluate("void addLink('subjects')"); await pg.wait_for_timeout(250)
    await pg.fill('#dlg input[name=url]','https://math.test'); await pg.fill('#dlg input[name=title]','سلايدات'); await pg.click('[data-ok="1"]'); await pg.wait_for_timeout(500)
    ok('link inside subject',await pg.evaluate("allLinks(S.subjects).length===1"))
    await pg.screenshot(path='/downloads/shot_subj_inside.png')

    await pg.evaluate("void addToSubject(['V1'])"); await pg.wait_for_timeout(300)
    await pg.click('[data-ok="1"]'); await pg.wait_for_timeout(400)
    ok('vault folder copied into subject',await pg.evaluate("S.subjects[0].children.some(n=>n.title==='شغل')&&S.vault.some(n=>n.id==='V1')"))

    await pg.evaluate("void quickNote('L2')"); await pg.wait_for_timeout(250)
    await pg.fill('#dlg textarea[name=note]','افتحه قبل المحاضرة'); await pg.click('[data-ok="1"]'); await pg.wait_for_timeout(300)
    ok('note saved',await pg.evaluate("find('L2').n.note==='افتحه قبل المحاضرة'"))
    await pg.click('nav button[data-tab="vault"]'); await pg.wait_for_timeout(400)
    ok('note shown on card',await pg.evaluate("document.querySelector('#main').innerText.includes('افتحه قبل المحاضرة')"))
    ok('note searchable',await pg.evaluate("searchAll(S.vault,'المحاضرة').length===1"))
    await pg.screenshot(path='/downloads/shot_note.png')

    await pg.keyboard.press('Control+k'); await pg.wait_for_timeout(200)
    ok('Ctrl+K focuses search',await pg.evaluate("document.activeElement&&document.activeElement.id==='search'"))
    await pg.evaluate("UI.q='example';UI.qAll=true;render()"); await pg.wait_for_timeout(300)
    ok('global search groups',await pg.evaluate("document.querySelector('#main').innerText.includes('المواد')&&document.querySelector('#main').innerText.includes('الخزنة')"))
    await pg.evaluate("UI.q='math';UI.qSub=S.subjects[0].id;render()"); await pg.wait_for_timeout(300)
    ok('subject filter narrows results',await pg.evaluate("document.querySelector('#main').innerText.includes('سلايدات')&&!document.querySelector('#main').innerText.includes('Example')"))
    await pg.screenshot(path='/downloads/shot_search_scope.png')
    await pg.evaluate("UI.q='';UI.qAll=false;UI.qSub='';render()"); await pg.wait_for_timeout(200)

    await pg.evaluate("S.imports=[{kind:'folder',browser:'LibreWolf',title:'LibreWolf',color:'#7c5cff',shape:0,children:[{kind:'link',id:'A1',title:'A old name',url:'https://a.test',tags:['مهم'],note:'ملاحظتي'},{kind:'link',id:'B1',title:'B',url:'https://b.test'}]}];prep(S.imports);S.counters={LibreWolf:1};render()")
    html='<!DOCTYPE NETSCAPE-Bookmark-file-1><DL><p><DT><A HREF="https://a.test" ADD_DATE="1">A new</A><DT><A HREF="https://c.test" ADD_DATE="2">C</A></DL>'
    await pg.evaluate("UI.tab='imports';UI.ipath=[];render()"); await pg.wait_for_timeout(200)
    await pg.evaluate("(h)=>{const f=new File([h],'b.html',{type:'text/html'});document.querySelector('#brsel').value='LibreWolf';window._imp=importFile(f)}",html)
    await pg.wait_for_timeout(500)
    ok('import asks new/over',await pg.evaluate("!!document.querySelector('#dlg input[name=mode][value=over]')"))
    await pg.screenshot(path='/downloads/shot_import_choice.png')
    await pg.check('#dlg input[name=mode][value=over]'); await pg.click('[data-ok="1"]'); await pg.wait_for_timeout(400)
    ok('overwrite confirmation shown',await pg.evaluate("document.querySelector('#dlg').innerText.includes('هتكتب فوق')"))
    await pg.screenshot(path='/downloads/shot_import_confirm.png')
    await pg.click('[data-ok="1"]'); await pg.wait_for_timeout(500)
    r=await pg.evaluate("(()=>{const k=S.imports[0].children;const a=k.find(x=>x.url==='https://a.test')||{};return [S.imports.length,k.length,allLinks(S.imports).map(l=>l.url).sort(),a.tags||[],a.note||'']})()")
    print(r)
    ok('overwrite replaces tree (A kept, C added, B gone)',r[0]==1 and r[1]==2 and 'https://c.test' in r[2] and 'https://b.test' not in r[2],r)
    ok('tags survive overwrite',r[3]==['مهم'],r[3])
    ok('note survives overwrite',r[4]=='ملاحظتي',r[4])
    await pg.evaluate("undo()"); await pg.wait_for_timeout(300)
    ok('undo restores pre-import tree',await pg.evaluate("S.imports[0].children.length===2&&allLinks(S.imports).some(l=>l.url==='https://b.test')"))
    await pg.screenshot(path='/downloads/shot_import_after.png')

    await pg.evaluate("(h)=>{const f=new File([h],'b.html',{type:'text/html'});document.querySelector('#brsel').value='LibreWolf';window._imp=importFile(f)}",html)
    await pg.wait_for_timeout(400); await pg.click('[data-ok="1"]'); await pg.wait_for_timeout(400)
    ok('import as new adds a second root',await pg.evaluate("S.imports.length===2"))

    await pg.evaluate("B.export=async(n,b64)=>{window._exp={n:n,size:(b64||'').length};return n};0")
    await pg.evaluate("UI.tab='vault';UI.path=[];render();void exportDlg('html')"); await pg.wait_for_timeout(300)
    await pg.select_option('#xsc','pick'); await pg.click('[data-ok="1"]'); await pg.wait_for_timeout(400)
    ok('picker tree lists folders and links',await pg.evaluate("document.querySelectorAll('#dlg input[name^=p_]').length>=3"),await pg.evaluate("document.querySelectorAll('#dlg input[name^=p_]').length"))
    await pg.screenshot(path='/downloads/shot_pick_tree.png')
    await pg.check('#dlg input[name="p_V1"]'); await pg.click('[data-ok="1"]'); await pg.wait_for_timeout(700)
    ok('export ran with picked folder',await pg.evaluate("!!window._exp&&window._exp.n==='raabt-bookmarks.html'"))

    await pg.evaluate("B.saveTo=async(n,d,dir)=>{(window._bks=window._bks||[]).push({n:n,dir:dir,len:(d||'').length});return true};0")
    await pg.evaluate("void doBackup(true,'pick',[find('V1').n])"); await pg.wait_for_timeout(300)
    ok('picked backup written',await pg.evaluate("(window._bks||[]).some(x=>x.n==='raabt-backup-pick.json')"),await pg.evaluate("window._bks"))
    ok('picked backup has picked state',await pg.evaluate("JSON.parse(backupJson('pick',[find('V1').n])).state.picked.length===1"))

    await pg.click('nav button[data-tab="settings"]'); await pg.wait_for_timeout(400)
    ok('backup location field present',await pg.evaluate("!!document.querySelector('#bkdir')"))
    await pg.select_option('select[data-act=bk]','hours'); await pg.wait_for_timeout(300)
    ok('hours field appears',await pg.evaluate("!!document.querySelector('#bkh')"))
    await pg.fill('#bkh','3'); await pg.dispatch_event('#bkh','change'); await pg.wait_for_timeout(200)
    ok('hours stored',await pg.evaluate("S.settings.bkHours===3"))
    ok('dueBackup uses hours',await pg.evaluate("S.settings.lastBackup=Date.now()-4*3600e3;dueBackup()===true"))
    await pg.screenshot(path='/downloads/shot_settings_backup.png')
    await pg.evaluate("S.settings.bkDir='/tmp';persist();void doBackup(true,'vault')"); await pg.wait_for_timeout(300)
    ok('backup honours chosen folder',await pg.evaluate("(window._bks||[]).some(x=>x.n==='raabt-backup-vault.json'&&x.dir==='/tmp')"),await pg.evaluate("window._bks"))

    await pg.click('nav button[data-tab="vault"]'); await pg.wait_for_timeout(300)
    await pg.evaluate("void deadCheck()"); await pg.wait_for_timeout(300)
    ok('dead check asks scope',await pg.evaluate("!!document.querySelector('#dlg select[name=sc]')"))
    await pg.click('#dlg [data-x]')

    print('errors',errs,sum(R),'/',len(R)); await b.close()
asyncio.run(main())
